    // MARK: User auth requests

    func testUserAuthRequestUsesSHA2AlgorithmAndVerifies() throws {
        let pairs: [(NIOSSHPrivateKey.RSASignatureAlgorithm, NIOSSHPrivateKey.RSASignatureAlgorithm)] = [
            (.sha256, .sha512), (.sha512, .sha256),
        ]
        for (algorithm, otherAlgorithm) in pairs {
            let key = try self.rsaKey(algorithm)
            let offer = NIOSSHUserAuthenticationOffer(
                username: "user",
                serviceName: "ssh-connection",
                offer: .privateKey(.init(privateKey: key))
            )
            let request = try SSHMessage.UserAuthRequestMessage(request: offer, sessionID: self.sessionID())

            guard case .publicKey(.rsaSHA2(let publicKey, let requestAlgorithm, .some(let signature))) = request.method
            else {
                XCTFail("Unexpected method \(request.method)")
                continue
            }
            XCTAssertEqual(requestAlgorithm, algorithm)
            XCTAssertEqual(publicKey, key.publicKey)

            let payload = UserAuthSignablePayload(
                sessionIdentifier: self.sessionID(),
                userName: "user",
                serviceName: "ssh-connection",
                publicKey: publicKey,
                rsaSignatureAlgorithm: algorithm
            )
            XCTAssertTrue(publicKey.isValidSignature(signature, for: payload))

            // The same signature must not verify for a payload naming the other algorithm.
            let otherPayload = UserAuthSignablePayload(
                sessionIdentifier: self.sessionID(),
                userName: "user",
                serviceName: "ssh-connection",
                publicKey: publicKey,
                rsaSignatureAlgorithm: otherAlgorithm
            )
            XCTAssertFalse(publicKey.isValidSignature(signature, for: otherPayload))

            // On the wire, the request names the SHA-2 algorithm while the blob keeps the ssh-rsa format.
            var buffer = ByteBuffer()
            buffer.writeSSHMessage(.userAuthRequest(request))
            XCTAssertEqual(buffer.readInteger(as: UInt8.self), SSHMessage.UserAuthRequestMessage.id)
            XCTAssertEqual(buffer.readSSHString().map { String(buffer: $0) }, "user")
            XCTAssertEqual(buffer.readSSHString().map { String(buffer: $0) }, "ssh-connection")
            XCTAssertEqual(buffer.readSSHString().map { String(buffer: $0) }, "publickey")
            XCTAssertEqual(buffer.readSSHBoolean(), true)
            XCTAssertEqual(buffer.readSSHString().map { String(buffer: $0) }, algorithm.description)
            var blob = buffer.readSSHString()
            XCTAssertEqual(blob?.readSSHString().map { String(buffer: $0) }, "ssh-rsa")
            var signatureBlob = buffer.readSSHString()
            XCTAssertEqual(signatureBlob?.readSSHString().map { String(buffer: $0) }, algorithm.description)

            XCTAssertEqual(try self.roundTrip(.userAuthRequest(request)), .userAuthRequest(request))
        }
    }

    func testUserAuthRequestPartialReadsReturnNil() throws {
        let key = try self.rsaKey(.sha256)
        let offer = NIOSSHUserAuthenticationOffer(
            username: "user",
            serviceName: "ssh-connection",
            offer: .privateKey(.init(privateKey: key))
        )
        let message = SSHMessage.userAuthRequest(
            try .init(request: offer, sessionID: self.sessionID())
        )
        var full = ByteBuffer()
        full.writeSSHMessage(message)
        let bytes = Array(full.readableBytesView)

        var buffer = ByteBuffer()
        for byte in bytes.dropLast() {
            buffer.writeInteger(byte)
            XCTAssertNil(try buffer.readSSHMessage())
        }
        buffer.writeInteger(bytes.last!)
        XCTAssertEqual(try buffer.readSSHMessage(), message)
    }

    private func signedRequestBytes(
        algorithmName: String,
        signatureAlgorithm: NIOSSHPrivateKey.RSASignatureAlgorithm,
        key: NIOSSHPublicKey? = nil
    ) throws -> ByteBuffer {
        let signingKey = try self.rsaKey(signatureAlgorithm)
        let payload = UserAuthSignablePayload(
            sessionIdentifier: self.sessionID(),
            userName: "user",
            serviceName: "ssh-connection",
            publicKey: signingKey.publicKey,
            rsaSignatureAlgorithm: signatureAlgorithm
        )
        let signature = try signingKey.sign(payload)

        var buffer = ByteBuffer()
        buffer.writeInteger(SSHMessage.UserAuthRequestMessage.id)
        buffer.writeSSHString("user".utf8)
        buffer.writeSSHString("ssh-connection".utf8)
        buffer.writeSSHString("publickey".utf8)
        buffer.writeSSHBoolean(true)
        buffer.writeSSHString(algorithmName.utf8)
        buffer.writeCompositeSSHString { $0.writeSSHHostKey(key ?? signingKey.publicKey) }
        buffer.writeCompositeSSHString { $0.writeSSHSignature(signature) }
        return buffer
    }

    func testUserAuthRequestWithMismatchedSignatureAlgorithmIsRejected() throws {
        var buffer = try self.signedRequestBytes(algorithmName: "rsa-sha2-512", signatureAlgorithm: .sha256)
        XCTAssertThrowsError(try buffer.readSSHMessage()) { error in
            XCTAssertEqual((error as? NIOSSHError)?.type, .invalidSSHMessage)
        }
    }

    func testUserAuthRequestWithSHA2AlgorithmAndNonRSAKeyIsRejected() throws {
        var buffer = try self.signedRequestBytes(
            algorithmName: "rsa-sha2-256",
            signatureAlgorithm: .sha256,
            key: NIOSSHPrivateKey(ed25519Key: .init()).publicKey
        )
        XCTAssertThrowsError(try buffer.readSSHMessage()) { error in
            XCTAssertEqual((error as? NIOSSHError)?.type, .invalidSSHMessage)
        }
    }

    func testSHA1RSAUserAuthRequestIsTreatedAsUnknown() throws {
        // `ssh-rsa` as the algorithm name means SHA-1; it is not supported and must not be verified.
        var buffer = try self.signedRequestBytes(algorithmName: "ssh-rsa", signatureAlgorithm: .sha256)
        guard case .some(.userAuthRequest(let request)) = try buffer.readSSHMessage() else {
            XCTFail("Expected a user auth request")
            return
        }
        XCTAssertEqual(request.method, .publicKey(.unknown))
    }

    func testSHA1RSASignatureBlobIsRejected() throws {
        var buffer = ByteBuffer()
        buffer.writeSSHString("ssh-rsa".utf8)
        buffer.writeSSHString([UInt8](repeating: 1, count: 256))
        XCTAssertThrowsError(try buffer.readSSHSignature()) { error in
            XCTAssertEqual((error as? NIOSSHError)?.type, .unknownSignature)
        }
    }

    func testOversizedRSASignatureIsRejected() throws {
        var buffer = ByteBuffer()
        buffer.writeSSHString("rsa-sha2-512".utf8)
        buffer.writeSSHString([UInt8](repeating: 1, count: 1025))
        XCTAssertThrowsError(try buffer.readSSHSignature()) { error in
            XCTAssertEqual((error as? NIOSSHError)?.type, .invalidSSHMessage)
        }
