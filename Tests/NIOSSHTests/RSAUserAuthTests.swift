    func testTamperedRSASignatureDoesNotVerify() throws {
        let key = try self.rsaKey(.sha512)
        let payload = UserAuthSignablePayload(
            sessionIdentifier: self.sessionID(),
            userName: "user",
            serviceName: "ssh-connection",
            publicKey: key.publicKey,
            rsaSignatureAlgorithm: .sha512
        )
        guard case .rsa(let algorithm, let signature) = try key.sign(payload).backingSignature else {
            XCTFail("Expected an RSA signature")
            return
        }
        var bytes = Array(signature.rawRepresentation)
        bytes[bytes.count / 2] ^= 0x01
        let tampered = NIOSSHSignature(
            backingSignature: .rsa(algorithm, .init(rawRepresentation: bytes))
        )
        XCTAssertFalse(key.publicKey.isValidSignature(tampered, for: payload))
    }

    // MARK: Unsupported usages

    func testRSAKeysAreNotHostKeys() throws {
        let key = try self.rsaKey(.sha512)
        XCTAssertEqual(key.hostKeyAlgorithms, [])
        XCTAssertThrowsError(try key.sign(digest: SHA256.hash(data: [1, 2, 3]))) { error in
            XCTAssertEqual((error as? NIOSSHError)?.type, .unsupportedKeyUsage)
        }

        let payload = UserAuthSignablePayload(
            sessionIdentifier: self.sessionID(),
            userName: "user",
            serviceName: "ssh-connection",
            publicKey: key.publicKey,
            rsaSignatureAlgorithm: .sha512
        )
        let signature = try key.sign(payload)
        let digest = SHA512.hash(data: payload.bytes.readableBytesView)
        XCTAssertFalse(key.publicKey.isValidSignature(signature, for: digest))
    }

    func testRSAKeysCannotBeCertified() throws {
        let caKey = NIOSSHPrivateKey(ed25519Key: .init())
        XCTAssertThrowsError(
            try NIOSSHCertifiedPublicKey(
                nonce: ByteBuffer(bytes: [1, 2, 3]),
                serial: 1,
                type: .user,
                key: self.rsaKey(.sha512).publicKey,
                keyID: "id",
                validPrincipals: [],
                validAfter: 0,
                validBefore: .max,
                criticalOptions: [:],
                extensions: [:],
                signatureKey: caKey.publicKey,
                signature: caKey.sign(digest: SHA256.hash(data: [1]))
            )
        ) { error in
            XCTAssertEqual((error as? NIOSSHError)?.type, .invalidCertificate)
        }
    }

    // MARK: End to end

    func testRSAUserAuthenticationEndToEnd() throws {
        for algorithm in [NIOSSHPrivateKey.RSASignatureAlgorithm.sha256, .sha512] {
            let channel = BackToBackEmbeddedChannel()
            defer { XCTAssertNoThrow(try channel.finish()) }

            let key = try self.rsaKey(algorithm)
            var harness = TestHarness()
            harness.clientAuthDelegate = PrivateKeyClientAuth(key)
            harness.serverAuthDelegate = ExpectPublicKeyAuth(key.publicKey)

            XCTAssertNoThrow(try channel.configureWithHarness(harness))
            XCTAssertNoThrow(try channel.activate())
            XCTAssertNoThrow(try channel.interactInMemory())

            _ = try channel.createNewChannel()
            XCTAssertNoThrow(try channel.interactInMemory())
            XCTAssertEqual(channel.activeServerChannels.count, 1, "\(algorithm) did not authenticate")
        }
    }

    func testRSAUserAuthenticationWithWrongKeyFails() throws {
        let channel = BackToBackEmbeddedChannel()
        defer { XCTAssertNoThrow(try channel.finish()) }

        let otherKey = try _RSA.Signing.PrivateKey(keySize: .bits2048)
        var harness = TestHarness()
        harness.clientAuthDelegate = PrivateKeyClientAuth(try self.rsaKey(.sha512))
        let serverDelegate = RecordingPublicKeyAuth(try self.rsaKey(.sha512, key: otherKey).publicKey)
        harness.serverAuthDelegate = serverDelegate

        XCTAssertNoThrow(try channel.configureWithHarness(harness))
        XCTAssertNoThrow(try channel.activate())
        XCTAssertNoThrow(try channel.interactInMemory())

        // The signature is valid, so the request reaches the server delegate, which rejects the unknown key.
        XCTAssertEqual(serverDelegate.outcomes, [false])
        XCTAssertEqual(channel.activeServerChannels.count, 0)
    }
}

/// Accepts one public key and records whether each public key request matched it.
private final class RecordingPublicKeyAuth: NIOSSHServerUserAuthenticationDelegate {
    private let key: NIOSSHPublicKey
    private(set) var outcomes: [Bool] = []

    init(_ key: NIOSSHPublicKey) {
        self.key = key
    }

    let supportedAuthenticationMethods: NIOSSHAvailableUserAuthenticationMethods = .publicKey

    func requestReceived(
        request: NIOSSHUserAuthenticationRequest,
        responsePromise: EventLoopPromise<NIOSSHUserAuthenticationOutcome>
    ) {
        guard case .publicKey(let actualKey) = request.request else {
            responsePromise.succeed(.failure)
            return
        }
        let matches = actualKey.publicKey == self.key
        self.outcomes.append(matches)
        responsePromise.succeed(matches ? .success : .failure)
    }
}
