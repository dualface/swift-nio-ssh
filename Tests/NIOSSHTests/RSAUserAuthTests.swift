    private func sessionID() -> ByteBuffer {
        ByteBuffer(bytes: Array(SHA256.hash(data: Array("session".utf8))))
    }

    private func rsaKey(
        _ algorithm: NIOSSHPrivateKey.RSASignatureAlgorithm,
        key: _RSA.Signing.PrivateKey = RSAUserAuthTests.sharedRSAKey
    ) throws -> NIOSSHPrivateKey {
        try NIOSSHPrivateKey(rsaKey: key, signatureAlgorithm: algorithm)
    }

    private func encodedRSABlob(exponent: [UInt8], modulus: [UInt8]) -> String {
        var buffer = ByteBuffer()
        buffer.writeSSHString("ssh-rsa".utf8)
        buffer.writeSSHString(exponent)
        buffer.writeSSHString(modulus)
        return "ssh-rsa " + Data(buffer.readableBytesView).base64EncodedString()
    }

    private func roundTrip(_ message: SSHMessage) throws -> SSHMessage? {
        var buffer = ByteBuffer()
        buffer.writeSSHMessage(message)
        return try buffer.readSSHMessage()
    }

    // MARK: Public key format

    func testOpenSSHRSAPublicKeyRoundTrips() throws {
        let key = try NIOSSHPublicKey(openSSHPublicKey: Self.openSSH2048PublicKey + " comment")
        XCTAssertEqual(String(openSSHPublicKey: key), Self.openSSH2048PublicKey)
        XCTAssertEqual(try NIOSSHPublicKey(openSSHPublicKey: String(openSSHPublicKey: key)), key)
    }

    func testRSAPublicKeyBlobUsesSSHRSAFormatForAllSupportedSizes() throws {
        for keySize in [_RSA.Signing.KeySize.bits2048, .bits3072, .bits4096] {
            let rsa = try _RSA.Signing.PrivateKey(keySize: keySize)
            let publicKey = try self.rsaKey(.sha512, key: rsa).publicKey

            var buffer = ByteBuffer()
            buffer.writeSSHHostKey(publicKey)
            XCTAssertEqual(buffer.readSSHString().map { String(buffer: $0) }, "ssh-rsa")
            let primitives = try rsa.publicKey.getKeyPrimitives()
            let exponent = try buffer.readRSAPositiveMPInt(maximumBytes: 4)
            let modulus = try buffer.readRSAPositiveMPInt(maximumBytes: 1024)
            XCTAssertEqual(exponent.map(Array.init), Array(primitives.publicExponent.drop(while: { $0 == 0 })))
            XCTAssertEqual(modulus.map(Array.init), Array(primitives.modulus.drop(while: { $0 == 0 })))
            XCTAssertEqual(buffer.readableBytes, 0)
        }
    }

    func testRSAPublicKeysOutsideLimitsAreRejected() throws {
        let modulus2048 = [UInt8](repeating: 0xC1, count: 256)
        let oversizedModulus = [UInt8](repeating: 0x41, count: 1025)
        var evenModulus = modulus2048
        evenModulus[evenModulus.count - 1] = 0xC0

        let invalidKeys = [
            Self.openSSH1024PublicKey,
            self.encodedRSABlob(exponent: [0x01, 0x00, 0x01], modulus: [0x00] + oversizedModulus),
            self.encodedRSABlob(exponent: [0x01, 0x00, 0x01], modulus: [0x00] + evenModulus),
            self.encodedRSABlob(exponent: [0x01, 0x00, 0x00], modulus: [0x00] + modulus2048),
            self.encodedRSABlob(exponent: [0x01], modulus: [0x00] + modulus2048),
            self.encodedRSABlob(exponent: [0x01, 0x00, 0x00, 0x00, 0x01], modulus: [0x00] + modulus2048),
            // Negative modulus: the high bit is set without a leading zero byte.
            self.encodedRSABlob(exponent: [0x01, 0x00, 0x01], modulus: modulus2048),
            // Non-minimal encodings and zero.
            self.encodedRSABlob(exponent: [0x00, 0x01, 0x00, 0x01], modulus: [0x00] + modulus2048),
            self.encodedRSABlob(exponent: [0x01, 0x00, 0x01], modulus: []),
        ]

        for (index, key) in invalidKeys.enumerated() {
            XCTAssertThrowsError(try NIOSSHPublicKey(openSSHPublicKey: key), "key \(index) was accepted")
        }
    }

    func testTruncatedRSAPublicKeyIsRejected() throws {
        var components = Self.openSSH2048PublicKey.split(separator: " ")
        let blob = Data(base64Encoded: String(components[1]))!
        components[1] = Substring(blob.dropLast(10).base64EncodedString())
        XCTAssertThrowsError(try NIOSSHPublicKey(openSSHPublicKey: components.joined(separator: " ")))
    }

    func testRSAPrivateKeysBelowMinimumSizeAreRejected() throws {
